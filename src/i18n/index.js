  function formatMessage(locale, value, { includeDetail = false } = {}) {
    if (value == null) return '';
    if (typeof value === 'string' || typeof value === 'number') return String(value);
    if (value.key) {
      const params = Object.fromEntries(Object.entries(value.params || {}).map(([name, param]) =>
        [name, param && typeof param === 'object' ? formatMessage(locale, param) : param]));
      const text = t(locale, value.key, params);
      return includeDetail && value.detail && value.detail !== text
        ? `${text}\n${t(locale, 'error.details', { detail: value.detail })}` : text;
    }
    if (value.i18nKey) return t(locale, value.i18nKey, value.i18nParams);
    if (typeof value.message === 'string') return value.message;
    return '';
  }

