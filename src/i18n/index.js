  const messages = Object.freeze({ en: Object.freeze(en), 'zh-CN': Object.freeze(zhCN) });

  function resolveLocale(language, systemLocale = 'en') {
    if (language === 'zh-CN' || language === 'en') return language;
    return /^zh(?:-|_|$)/i.test(String(systemLocale || '')) ? 'zh-CN' : 'en';
  }

  function interpolate(template, params = {}) {
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
  }

  function t(locale, key, params) {
    const resolved = resolveLocale(locale, locale);
    const template = messages[resolved]?.[key] ?? messages.en[key] ?? key;
    return interpolate(template, params);
  }

  function message(key, params = {}, detail) {
    return { key, params, ...(detail ? { detail: String(detail) } : {}) };
  }

  function createError(code, key, params = {}, detail) {
    const error = new Error(t('en', key, params));
    error.code = code;
    error.i18nKey = key;
    error.i18nParams = params;
    if (detail) error.detail = String(detail);
    return error;
  }

  function serializeError(error, fallbackKey = 'error.unknown') {
    if (error && typeof error === 'object' && error.key) return error;
    const detail = error?.detail || error?.message || String(error || '');
    const mapped = classifyError(detail);
    const byCode = {
      INVALID_PS5_IP: 'error.invalidPs5Ip', INVALID_PS5_PORT: 'error.invalidPs5Port',
      INVALID_PKG_FILE: 'error.pkgInvalid', INVALID_PKG_FORMAT: 'error.pkgInvalid',
      PKG_CHANGED: 'error.pkgChanged', PKG_INELIGIBLE: 'error.pkgIneligible',
      MANAGER_BUSY: 'error.managerBusy', UNRECOGNIZED_MANAGER: 'error.managerUnrecognized',
      UNSUPPORTED_MANAGER_VERSION: 'error.managerUnrecognized', BAD_MANAGER_RESPONSE: 'error.managerUnrecognized',
      UNVERIFIED_PAYLOAD_MANAGER_VERSION: 'remote.payloadManagerVersion',
      BAD_PAYLOAD_MANAGER_RESPONSE: 'remote.payloadManagerResponse',
      PAYLOAD_MANAGER_HTTP: 'remote.payloadManagerResponse',
      INSTALL_FAILED: 'error.installFailed', RESULT_UNCONFIRMED: 'error.resultUnconfirmed',
      UPLOAD_STALLED: 'error.uploadStalled', TASK_CANCELED: 'remote.canceled',
    };
    return {
      code: error?.code || 'UNKNOWN_ERROR',
      key: error?.i18nKey || byCode[error?.code] || (error?.name === 'AbortError' ? 'source.canceled' : mapped?.key) || fallbackKey,
      params: error?.i18nParams || mapped?.params || {},
      ...(detail ? { detail: String(detail) } : {}),
    };
  }

